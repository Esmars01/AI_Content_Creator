def _exact_boundaries(raw: str, script: str, starts: list[str]) -> tuple[dict[str, int], list[int]]:
    """The script span in `raw` and the absolute offsets where the given segment openings start."""
    base = raw.index(script)
    offsets = [base + script.index(opening) for opening in starts]
    return {"start": base, "end": base + len(script)}, offsets


