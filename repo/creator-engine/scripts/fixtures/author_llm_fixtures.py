class Script:
    """Segments in order (seg_1, seg_2, …) with word lookups by text."""

    def __init__(self, *lines: str) -> None:
        self.lines = list(lines)

    def key(self, i: int) -> str:
        return f"seg_{i + 1}"

    def w(self, seg: int, word: str, nth: int = 0) -> dict[str, Any]:
        """{segment_key, word} of the nth occurrence of `word` (case- and punctuation-insensitive)."""
        tokens = tokenize(self.lines[seg - 1])
        hits = [t.index for t in tokens if t.norm == word.lower()]
        if len(hits) <= nth:
            raise KeyError(f"{word!r} (#{nth}) not in seg_{seg}: {[t.norm for t in tokens]}")
        return {"segment_key": f"seg_{seg}", "word": hits[nth]}

    def first(self, seg: int) -> dict[str, Any]:
        return {"segment_key": f"seg_{seg}", "word": 0}

    def words(self) -> int:
        return sum(len(tokenize(line)) for line in self.lines)


def strategies(
    prosody: str,
    gaze: str,
    gesture: str,
    posture: str,
    reaction: str = "none",
    camera_awareness: str = "direct_address",
) -> dict[str, str]:
    return {
        "prosody": prosody,
        "gaze": gaze,
        "gesture": gesture,
        "posture": posture,
        "reaction": reaction,
        "camera_awareness": camera_awareness,
    }


def state(
    start: dict[str, Any] | None,
    *,
    internal: str,
    social: str,
    audience: str,
    perf: str,
    displayed: tuple[str, float],
    felt: tuple[str, float] | None = None,
    masking: bool = False,
    strat: dict[str, str],
    delta: float = 0.0,
    attention: str = "camera",
    transition: dict[str, Any] | None = None,
    priority: str = "should",
    start_s: float | None = None,
    description: str = "",
) -> dict[str, Any]:
    felt = felt or displayed
    out: dict[str, Any] = {
        "internal_state": internal,
        "internal_description": description,
        "social_goal": social,
        "audience_goal": audience,
        "performance_intent": perf,
        "felt": {"label": felt[0], "intensity": felt[1]},
        "displayed": {"label": displayed[0], "intensity": displayed[1]},
        "masking": masking,
        "confidence_delta": delta,
        "attention_target": attention,
        "strategies": strat,
        "transition": transition,
        "priority": priority,
    }
    if start_s is not None:
        out["start_s"] = start_s
    else:
        out["start"] = start
    return out


def trigger(kind: str, at: dict[str, Any], description: str, style: str = "sudden") -> dict[str, Any]:
    return {"style": style, "trigger_kind": kind, "trigger_at": at, "description": description, "duration_words": 1}


def event(type_: str, at: dict[str, Any], **kw: Any) -> dict[str, Any]:
    return {"type": type_, "at": at, **kw}


def intent(**kw: Any) -> dict[str, Any]:
    return kw


